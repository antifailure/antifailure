export interface WebhookOptions {
  url: string
  /** Used to sign the body, so the receiver can tell a delivery from this
   *  control plane from anything else that learned the URL. */
  secret: string
  fetch: Fetcher
}

/**
 * A signed webhook, for everything with no adapter.
 *
 * The signature covers the body and a timestamp, and the timestamp is outside
 * the body so a receiver can reject an old delivery without parsing it. A
 * signature over the body alone is replayable forever.
 */
export class WebhookSink implements Sink {
  private readonly opts: WebhookOptions

  constructor(opts: WebhookOptions) {
    this.opts = opts
  }

  name(): string {
    return 'webhook'
  }

  async deliver(batch: Batch): Promise<void> {
    const body = JSON.stringify(batch)
    // Taken from the batch rather than from the clock, so that a redelivery of
    // the same batch carries the same signature and a receiver deduplicating on
    // it sees one delivery.
    const timestamp = batch.entries[0]?.occurredAt ?? ''
    const signature = createHmac('sha256', this.opts.secret)
      .update(`${timestamp}.${body}`)
      .digest('hex')

    await send(
      this.opts.fetch,
      this.opts.url,
      {
        method: 'POST',
        headers: {
          'content-type': 'application/json',
          'x-antifailure-timestamp': timestamp,
          'x-antifailure-signature': `sha256=${signature}`,
        },
        body,
      },
      'webhook',
    )
  }
}

/** Verifies a webhook delivery. Ships so that a receiver can check one without
 *  reimplementing the scheme from a documentation page. */
export function verifyWebhook(
  secret: string,
  timestamp: string,
  body: string,
  signature: string,
): boolean {
  const expected = `sha256=${createHmac('sha256', secret).update(`${timestamp}.${body}`).digest('hex')}`
  if (expected.length !== signature.length) return false
  let diff = 0
  for (let i = 0; i < expected.length; i += 1) {
    diff |= expected.charCodeAt(i) ^ signature.charCodeAt(i)
  }
  return diff === 0
}
