export interface EventHubsOptions {
  /** https://<namespace>.servicebus.windows.net/<hub>/messages */
  url: string
  /** A shared access signature. Generated by the caller so that the key never
   *  reaches this package and an operator can use managed identity instead. */
  authorization: string
  fetch: Fetcher
}

/** Azure Event Hubs, which takes a JSON array of records. */
export class EventHubsSink implements Sink {
  private readonly opts: EventHubsOptions

  constructor(opts: EventHubsOptions) {
    this.opts = opts
  }

  name(): string {
    return 'event-hubs'
  }

  async deliver(batch: Batch): Promise<void> {
    await send(
      this.opts.fetch,
      this.opts.url,
      {
        method: 'POST',
        headers: {
          authorization: this.opts.authorization,
          'content-type': 'application/vnd.microsoft.servicebus.json',
          'x-antifailure-manifest': JSON.stringify(batch.manifest),
        },
        body: JSON.stringify(batch.entries.map((entry) => ({ Body: entry }))),
      },
      'event hubs',
    )
  }
}

