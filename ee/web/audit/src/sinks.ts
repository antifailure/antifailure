export interface ObjectStoreOptions {
  /** Called with the object's key and body. Given rather than implemented,
   *  because S3 and Blob differ in their signing and neither belongs in a
   *  package about audit entries. */
  put: (key: string, body: string, contentType: string) => Promise<void>
  /** Prefix under which objects are written. */
  prefix?: string
}

/**
 * An object store, which is where an auditor usually wants the archive.
 *
 * The manifest is written as a second object beside the batch rather than
 * inside it, so that the batch file is exactly the newline-delimited JSON that
 * every log tool already reads, and the signature is still there for anybody
 * who wants to check it.
 *
 * The key is ordered by sequence and zero padded, so a listing sorts
 * chronologically. A key with a timestamp in it sorts chronologically too and
 * collides when two batches land in the same millisecond.
 */
export class ObjectStoreSink implements Sink {
  private readonly opts: ObjectStoreOptions

  constructor(opts: ObjectStoreOptions) {
    this.opts = opts
  }

  name(): string {
    return 'object-store'
  }

  async deliver(batch: Batch): Promise<void> {
    if (batch.entries.length === 0) return

    const prefix = this.opts.prefix ? `${this.opts.prefix.replace(/\/$/, '')}/` : ''
    const key =
      `${prefix}${batch.manifest.org}/` +
      `${String(batch.manifest.firstSeq).padStart(12, '0')}-` +
      `${String(batch.manifest.lastSeq).padStart(12, '0')}`

    await this.opts.put(
      `${key}.ndjson`,
      batch.entries.map((e) => JSON.stringify(e)).join('\n'),
      'application/x-ndjson',
    )
    await this.opts.put(
      `${key}.manifest.json`,
      JSON.stringify(batch.manifest, null, 2),
      'application/json',
    )
  }
}

