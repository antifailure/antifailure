//
// Not MIT. Covered by the Antifailure Enterprise License; see ee/LICENSE.md.
//
// Each is small on purpose. The queue in sink.ts holds all the behaviour that
// is hard to get right, so a sink is only "put these bytes there", and adding a
// new destination is a page rather than a project.
//
// Every one of them takes its transport as a parameter. That is not for
// testing, or not only: it is what lets an operator route through their own
// proxy, pin a certificate, or add a header their gateway requires, without
// this package growing an option for each.
//
// What none of them does is retry. Retrying is the queue's job, and a sink that
// also retried would multiply the two and turn a brief outage into a thundering
// herd against somebody's log endpoint.

import { createHmac } from 'node:crypto'
import { PermanentError, type Batch, type Sink } from './sink.ts'

/** The fetch a sink uses. */
export type Fetcher = (url: string, init: RequestInit) => Promise<Response>

/**
 * Decides whether a status means "never going to work".
 *
 * 401 and 403 are a credential nobody is going to fix by waiting, and 400, 404,
 * and 413 are the request itself. Retrying any of them forever is how a queue
 * fills with one batch that will never be accepted. Everything else, including
 * 429 and every 5xx, is temporary and the queue's backoff handles it.
 */
function permanent(status: number): boolean {
  return status === 400 || status === 401 || status === 403 || status === 404 || status === 413
}

async function send(
  fetcher: Fetcher,
  url: string,
  init: RequestInit,
  what: string,
): Promise<void> {
  let res: Response
  try {
    res = await fetcher(url, init)
  } catch (err) {
    // A transport failure is temporary by assumption. A hostname that does not
    // resolve looks the same as one that is briefly unreachable, and guessing
    // wrong towards permanent would discard entries over a DNS blip.
    throw new Error(`${what}: ${err instanceof Error ? err.message : String(err)}`)
  }
  if (res.ok) return

  // Bounded, because an error path must not read an unbounded body from an
  // endpoint that may not be the one intended.
  const body = (await res.text().catch(() => '')).slice(0, 500)
  const message = `${what} answered ${res.status}${body ? `: ${body}` : ''}`
  throw permanent(res.status) ? new PermanentError(message) : new Error(message)
}

