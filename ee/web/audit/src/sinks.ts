export interface SplunkOptions {
  /** The HTTP Event Collector endpoint, ending in /services/collector. */
  url: string
  token: string
  fetch: Fetcher
  /** Splunk's own index, source, and sourcetype, so entries land where the
   *  customer's existing searches already look rather than in main. */
  index?: string
  sourcetype?: string
}

/** Splunk's HTTP Event Collector, which takes newline-delimited JSON objects
 *  rather than an array. */
export class SplunkSink implements Sink {
  private readonly opts: SplunkOptions

  constructor(opts: SplunkOptions) {
    this.opts = opts
  }

  name(): string {
    return 'splunk'
  }

  async deliver(batch: Batch): Promise<void> {
    const body = batch.entries
      .map((entry) =>
        JSON.stringify({
          // Seconds, which is what HEC expects. Milliseconds are accepted and
          // silently interpreted as a date in the year 56000.
          time: Date.parse(entry.occurredAt) / 1000,
          host: 'antifailure',
          source: 'antifailure-audit',
          sourcetype: this.opts.sourcetype ?? 'antifailure:audit',
          ...(this.opts.index ? { index: this.opts.index } : {}),
          event: entry,
        }),
      )
      .join('\n')

    await send(
      this.opts.fetch,
      this.opts.url,
      {
        method: 'POST',
        headers: {
          authorization: `Splunk ${this.opts.token}`,
          'content-type': 'application/json',
          // The manifest travels in a header so that the body stays exactly
          // what Splunk expects and an operator can still check the batch.
          'x-antifailure-manifest': JSON.stringify(batch.manifest),
        },
        body,
      },
      'splunk',
    )
  }
}

