// reading one page
// -----------------------------------------------------------------------

// Reading is one bounded read, and an account of what it left out.
type Reading struct {
	Path        string
	Title       string
	Description string
	// Trail is the section that was read, or the page title for a whole page.
	Trail string
	// Anchor is the section that was read, empty for a whole page.
	Anchor string
	// Text is what was returned.
	Text                string
	FirstLine, LastLine int
	// TotalChars is the size of what was asked for, so a caller can see how
	// much of it arrived. ReturnedChars is what it got.
	TotalChars, ReturnedChars int
	Truncated                 bool
	// SectionsNotReturned names the anchors past the cut, which is what turns
	// a truncation into a next call rather than a dead end.
	SectionsNotReturned []string
	// NotReturnedChars is how much of what was asked for was withheld.
	NotReturnedChars int
	// Anchors are every section of the page, so one call can be followed by
	// an exact one.
	Anchors []string
}

// Read returns a page, or one of its sections, bounded to maxChars.
//
// The page and the heading are resolved by the caller rather than here, so
// that a path nobody ships and a section a page does not have are two
// different refusals. Reporting either as the other sends an agent to fix the
// wrong half of its call.
func Read(page *Page, section *Heading, maxChars int) *Reading {
	first, last := 1, len(page.Lines)
	trail, anchor := page.Title, ""
	if section != nil {
		first, last = section.FirstLine, section.LastLine
		trail, anchor = section.Trail, section.Anchor
	}

	full := page.Text(first, last)
	out := &Reading{
		Path: page.Path, Title: page.Title, Description: page.Description,
		Trail: trail, Anchor: anchor, Text: full,
		FirstLine: first, LastLine: last, TotalChars: len(full),
		Anchors: page.Anchors(), SectionsNotReturned: []string{},
	}
	if len(full) > maxChars {
		out.Truncated = true
		out.Text, _ = clipExcerpt(full, maxChars)
		// The last line actually returned, so LastLine is not a claim about
		// text nobody was given.
		out.LastLine = first + strings.Count(out.Text, "\n") - 1
		for _, h := range page.Headings {
			if h.FirstLine > out.LastLine && h.FirstLine <= last {
				out.SectionsNotReturned = append(out.SectionsNotReturned, h.Anchor)
			}
		}
	}
	out.ReturnedChars = len(out.Text)
	out.NotReturnedChars = out.TotalChars - len(strings.TrimSuffix(out.Text, "\n"+CutMarker))
	if out.NotReturnedChars < 0 {
		out.NotReturnedChars = 0
	}
	return out
}
