// Query is one search, with the budget the caller is willing to spend.
type Query struct {
	// Text is what the caller asked, in their own words.
	Text string
	// Section narrows to one top level group. Empty searches all of them.
	Section string
	// MaxResults and MaxChars are the caller's budget. MaxChars is the sum of
	// every excerpt in the answer, and it is honoured rather than advertised:
	// excerpts are shortened and then dropped to stay inside it, and whatever
	// was dropped is named.
	MaxResults int
	MaxChars   int
}

// A Hit is one page's best matching section, with the lines around the match.
type Hit struct {
	Path  string
	Title string
	// Trail is the heading path the excerpt came from, or the page title when
	// the match was above the first heading.
	Trail string
	// Anchor is what to pass to read this section, empty when the match was
	// above the first heading.
	Anchor string
	// FirstLine and LastLine locate the excerpt in the page.
	FirstLine, LastLine int
	// Excerpt is the lines around the match, bounded.
	Excerpt string
	// Clipped says the excerpt itself was cut to fit the budget.
	Clipped bool
	// OtherSections is how many further sections of this same page matched
	// and were not returned, so a caller knows the page has more to say.
	OtherSections int
	score         float64
}

// Results is what a search answers, including everything it did not answer.
type Results struct {
	Terms []string
	Hits  []Hit
	// PagesMatched is how many pages matched, before any budget was applied.
	PagesMatched int
	// SectionsMatched is how many sections across all of them matched.
	SectionsMatched int
	// PagesNotShown names the pages that matched and were left out, bounded
	// itself, with NotShownTotal carrying the true count.
	PagesNotShown []string
	NotShownTotal int
	// CharsUsed is the size of the excerpts actually returned, against the
	// budget that was asked for.
	CharsUsed, CharsBudget int
	// Truncated says plainly that something was withheld, whether a page was
	// dropped or an excerpt was cut.
	Truncated bool
}

// contextLines is how many lines either side of a match an excerpt carries.
//
// Three, measured against the real corpus rather than chosen: two cuts the
// header off a Markdown table and leaves a row with no column names, which is
// worse than not answering. Fixed rather than a parameter, because the knob a
// caller needs is the budget, and a second one that also changes the size
// makes the two able to disagree about which of them was honoured.
const contextLines = 3

// minExcerptChars is the smallest excerpt worth returning.
//
// Below this an excerpt is a fragment of a sentence, which is the shape of
// answer that reads as complete and is not. A budget too small for one of
// these returns no excerpt and says so, rather than half a line.
const minExcerptChars = 120

// maxPagesNamedAsNotShown bounds the list of what was left out, so that the
// note about truncation cannot itself become the thing that fills the answer.
const maxPagesNamedAsNotShown = 20

// Search finds the sections that answer a question and returns excerpts of
// them, inside the caller's budget.
func Search(q Query) Results { return load().search(q) }

func (ix *index) search(q Query) Results {
	terms := termsIn(q.Text)
	query := ix.compile(q.Text)
	out := Results{Terms: query.Terms, Hits: []Hit{}, PagesNotShown: []string{},
		CharsBudget: q.MaxChars}
	if len(terms) == 0 {
		return out
	}

	var ranked []Hit
	for _, p := range ix.pages {
		if q.Section != "" && p.Section != q.Section {
			continue
		}
		best, others := bestSection(query, p, terms)
		if best == nil {
			continue
		}
		best.OtherSections = others
		ranked = append(ranked, *best)
		out.SectionsMatched += others + 1
	}
	sort.SliceStable(ranked, func(i, j int) bool { return ranked[i].score > ranked[j].score })
	out.PagesMatched = len(ranked)

	used := 0
	for i := range ranked {
		hit := ranked[i]
		// What this hit may spend: an even share of what is LEFT, over the
		// slots still open. An even share of the whole budget instead would
		// cut the last excerpt while the budget still had room in it, which
		// is a truncation the caller paid for and did not need.
		//
		// A caller that lowers max_chars still gets shorter excerpts AND
		// fewer of them, which is what "less content" has to mean for the
		// budget to be worth asking for.
		perHit := q.MaxChars - used
		if slots := q.MaxResults - len(out.Hits); slots > 1 {
			perHit /= slots
		}
		if perHit < minExcerptChars {
			perHit = minExcerptChars
		}
		if len(out.Hits) >= q.MaxResults {
			out.PagesNotShown = appendNotShown(out.PagesNotShown, hit.Path)
			out.NotShownTotal++
			continue
		}
		excerpt, clipped := clipExcerpt(hit.Excerpt, perHit)
		if used+len(excerpt) > q.MaxChars {
			// The budget is spent. Everything from here on is named rather
			// than shortened further, because an excerpt below the floor is
			// not an answer.
			out.PagesNotShown = appendNotShown(out.PagesNotShown, hit.Path)
			out.NotShownTotal++
			continue
		}
		hit.Excerpt, hit.Clipped = excerpt, clipped
		used += len(excerpt)
		out.Hits = append(out.Hits, hit)
	}
	out.CharsUsed = used
	out.Truncated = out.NotShownTotal > 0
	for _, h := range out.Hits {
		if h.Clipped {
			out.Truncated = true
		}
	}
	return out
}

// appendNotShown adds a path to the bounded list of what was left out.
func appendNotShown(list []string, path string) []string {
	if len(list) >= maxPagesNamedAsNotShown {
		return list
	}
	return append(list, path)
}

// headingBonus is what a query word in the heading itself is worth, on top of
// the same word appearing in the section's text.
//
// A section whose heading carries the word is usually the answer, and without
// this the ranking is decided by how long a section is: a passing mention in
// four hundred lines outweighs a heading that names the thing.
const headingBonus = 3

// titleBonus is what a query word in the page's title or description is
// worth. It applies to the whole page rather than to one section of it.
const titleBonus = 4

// bestSection scores every section of a page and returns the best one, plus
// how many others matched.
func bestSection(q compiled, p *Page, terms map[string]int) (*Hit, int) {
	type candidate struct {
		hit   Hit
		score float64
	}
	var best *candidate
	matched := 0

	consider := func(trail, anchor, heading string, first, last int) {
		score, isHit := q.matches(p.Text(first, last))
		if !isHit {
			return
		}
		if heading != "" {
			headingScore, _ := q.score(heading)
			score += headingBonus * headingScore
		}
		matched++
		if best != nil && score <= best.score {
			return
		}
		firstLine, lastLine, excerpt := excerptAround(p, terms, first, last)
		best = &candidate{score: score, hit: Hit{
			Path: p.Path, Title: p.Title, Trail: trail, Anchor: anchor,
			FirstLine: firstLine, LastLine: lastLine, Excerpt: excerpt, score: score,
		}}
	}

	// The lead, meaning everything above the first heading. It is where a page
	// says what it is, so it is often the best answer on the page.
	lead := len(p.Lines)
	if len(p.Headings) > 0 {
		lead = p.Headings[0].FirstLine - 1
	}
	if lead > 0 {
		consider(p.Title, "", p.Title, 1, lead)
	}
	for _, h := range p.Headings {
		consider(h.Trail, h.Anchor, h.Text, h.FirstLine, h.LastLine)
	}
	if best == nil {
		return nil, 0
	}
	// The page's own title and description count for the whole page rather
	// than for one section of it, so they are added after the sections have
	// been compared against each other.
	pageScore, _ := q.score(p.Title + " " + p.Description)
	best.hit.score += titleBonus * pageScore
	return &best.hit, matched - 1
}

// compiled is one query, resolved against the corpus before anything is
// scored.
type compiled struct {
	// Terms are the words as the caller wrote them, for reporting.
	Terms []string
	// weight is every indexed word this query can match, mapped to what a
	// match is worth. A word's weight is the inverse of how many pages carry
	// it, which is what makes "what does stance mean" find the stance pages
	// rather than every page containing the word "does".
	//
	// There is no stopword list, and that is deliberate: a hand written list
	// of English function words would be wrong for a corpus where "load",
	// "run" and "check" are both ordinary words and product nouns, and it
	// would have to be maintained by somebody who remembered it existed.
	weight map[string]float64
	// selective is the subset of those words that appears in fewer than half
	// the pages. A hit has to match at least one of them.
	//
	// Without this every page in the corpus "matches" a question phrased as a
	// question, because "what" and "is" are in all of them, and an answer
	// saying 92 pages matched and 3 are shown is a truthful sentence that
	// tells the caller nothing. A word carried by half the corpus is not
	// evidence that a page is about anything.
	selective map[string]bool
	// anySelective says the query had a selective word at all. A query made
	// entirely of common words still gets an answer, ranked by the little the
	// words are worth, rather than nothing.
	anySelective bool
}

// nearVariantChars is how much longer a word may be than the query word it
// answers.
//
// Two characters, which covers the plural and the past tense: stance and
// stances, branch and branched, golden and goldens. It is a deliberately
// cheap stand in for a stemmer. The cost of getting it wrong is a slightly
// worse ranking, never a wrong answer, because the excerpt returned is the
// text itself.
const nearVariantChars = 2

// compile resolves a query against the corpus.
func (ix *index) compile(text string) compiled {
	asked := termsIn(text)
	out := compiled{
		Terms: sortedTerms(asked), weight: map[string]float64{},
		selective: map[string]bool{},
	}
	total := float64(len(ix.pages))
	if total < 1 {
		return out
	}
	for term := range asked {
		variants := ix.variantsOf(term)
		// How many PAGES this word could match at all, counting a page once
		// however many of its variants that page carries. Summing the per
		// variant counts instead would double count the pages carrying both
		// "stance" and "stances", which is most of the pages that are about
		// stances, and would make the word look common exactly where it is
		// most selective.
		pages := float64(ix.pagesCarryingAny(variants))
		if pages < 1 {
			continue
		}
		selective := pages*2 <= total
		if selective {
			out.anySelective = true
		}
		weight := math.Log(1 + total/pages)
		for _, v := range variants {
			// A word reached by two query words keeps the larger weight.
			if weight > out.weight[v] {
				out.weight[v] = weight
			}
			out.selective[v] = out.selective[v] || selective
		}
	}
	return out
}

// variantsOf returns the indexed words a query word answers: itself, the
// slightly longer forms of it, and the slightly shorter word it is a form of.
func (ix *index) variantsOf(term string) []string {
	var out []string
	for indexed := range ix.pagesWithTerm {
		switch {
		case indexed == term:
		case strings.HasPrefix(indexed, term) && len(indexed)-len(term) <= nearVariantChars:
		case strings.HasPrefix(term, indexed) && len(term)-len(indexed) <= nearVariantChars:
		default:
			continue
		}
		out = append(out, indexed)
	}
	sort.Strings(out)
	return out
}

// pagesCarryingAny counts the pages holding at least one of these words.
func (ix *index) pagesCarryingAny(variants []string) int {
	count := 0
	for _, p := range ix.pages {
		for _, v := range variants {
			if _, present := p.terms[v]; present {
				count++
				break
			}
		}
	}
	return count
}

// score weighs the query against a piece of text.
//
// The second return says whether a selective word matched, which is what
// separates a page that is about the question from a page that merely
// contains the word "is".
func (c compiled) score(text string) (float64, bool) {
	if strings.TrimSpace(text) == "" {
		return 0, false
	}
	score, selective := 0.0, false
	for word, hits := range termsIn(text) {
		weight, known := c.weight[word]
		if !known {
			continue
		}
		if c.selective[word] {
			selective = true
		}
		// Occurrences count with a sharply diminishing return: a section that
		// says the word five times is a better answer than one that says it
		// once, and not five times better.
		score += weight * (1 + math.Log(float64(hits)))
	}
	return score, selective
}

// matches reports whether a piece of text is a hit at all.
func (c compiled) matches(text string) (float64, bool) {
	score, selective := c.score(text)
	if score <= 0 {
		return 0, false
	}
	if c.anySelective && !selective {
		return score, false
	}
	return score, true
}

// excerptAround finds the densest run of lines inside a section and returns
// it with its context.
func excerptAround(p *Page, terms map[string]int, first, last int) (int, int, string) {
	bestLine, bestHits := first, -1
	for line := first; line <= last && line <= len(p.Lines); line++ {
		found := termsIn(p.Lines[line-1])
		hits := 0
		for term := range terms {
			hits += found[term]
		}
		if hits > bestHits {
			bestLine, bestHits = line, hits
		}
	}
	from, to := bestLine-contextLines, bestLine+contextLines
	if from < first {
		from = first
	}
	if to > last {
		to = last
	}
	return from, to, p.Text(from, to)
}

// CutMarker is the one sentence a cut leaves behind.
//
// A silently cut string is a string a reader believes is complete, and half a
// page read as a whole one is how a truncation becomes a wrong answer.
//
// Exported because the MCP tool that renders these results bounds its own
// output and has to leave room for exactly this, and a second copy of the
// sentence over there would be two descriptions of one thing, able to
// disagree the first time either is edited.
const CutMarker = "[cut here to fit the character budget]"

// clipExcerpt cuts text to the budget and says that it did.
//
// It cuts on a line boundary where it can, because half a line of Markdown is
// harder to read than one line fewer, and marks the cut either way.
func clipExcerpt(text string, max int) (string, bool) {
	if len(text) <= max {
		return text, false
	}
	cut := max
	if nl := strings.LastIndexByte(text[:max], '\n'); nl > max/2 {
		cut = nl
	}
	for cut > 0 && text[cut]&0xC0 == 0x80 {
		cut--
	}
	return strings.TrimRight(text[:cut], " \n") + "\n" + CutMarker, true
}

func sortedTerms(terms map[string]int) []string {
	out := make([]string, 0, len(terms))
	for t := range terms {
		out = append(out, t)
	}
	sort.Strings(out)
	return out
}

