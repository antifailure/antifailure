// parse reads one page into its frontmatter, its body and its headings.
func parse(path, raw string) *Page {
	front, body := splitFrontmatter(raw)
	page := &Page{
		Path:        path,
		Section:     sectionOf(path),
		Title:       frontmatterField(front, "title"),
		Description: frontmatterField(front, "description"),
		Body:        body,
		Lines:       strings.Split(body, "\n"),
	}
	if page.Title == "" {
		// Every page on this site has one, because Starlight refuses a page
		// without it. Falling back to the path rather than to an empty string
		// keeps a listing readable if that ever stops being true.
		page.Title = path
	}
	page.Headings = headingsIn(page.Lines, page.Title)
	return page
}

// splitFrontmatter removes the leading YAML block and returns both halves.
func splitFrontmatter(raw string) (front, body string) {
	if !strings.HasPrefix(raw, "---\n") {
		return "", raw
	}
	rest := raw[len("---\n"):]
	end := strings.Index(rest, "\n---\n")
	if end < 0 {
		return "", raw
	}
	return rest[:end], strings.TrimLeft(rest[end+len("\n---\n"):], "\n")
}

// frontmatterField reads one top level scalar out of the frontmatter.
//
// A line scan rather than a YAML parser, and the limit is stated rather than
// discovered later: it reads top level scalars only, so a nested
// "sidebar.order" is invisible here. Two fields are wanted, both are top level
// on every page of this site, and pulling a YAML dependency into the engine to
// read them would be a larger decision than the fields are worth.
func frontmatterField(front, name string) string {
	for _, line := range strings.Split(front, "\n") {
		if !strings.HasPrefix(line, name+":") {
			continue
		}
		value := strings.TrimSpace(strings.TrimPrefix(line, name+":"))
		value = strings.Trim(value, `"'`)
		return value
	}
	return ""
}

// sectionOf is the top level directory a page lives in.
func sectionOf(path string) string {
	if dir, _, found := strings.Cut(path, "/"); found {
		return dir
	}
	return "index"
}

// headingsIn finds the headings of a body, ignoring the ones inside fenced
// code blocks.
//
// The fence tracking is not fussiness. Several pages here show shell sessions
// whose comments begin with a hash, and reading those as headings would build
// a table of contents out of somebody's example script.
func headingsIn(lines []string, title string) []Heading {
	// openHeading is an ancestor of whatever is being read now.
	type openHeading struct {
		level int
		text  string
		at    int
	}
	var out []Heading
	var stack []openHeading
	used := map[string]int{}
	fence := ""

	for i, line := range lines {
		trimmed := strings.TrimSpace(line)
		switch {
		case fence != "":
			if strings.HasPrefix(trimmed, fence) {
				fence = ""
			}
			continue
		case strings.HasPrefix(trimmed, "```"):
			fence = "```"
			continue
		case strings.HasPrefix(trimmed, "~~~"):
			fence = "~~~"
			continue
		case !strings.HasPrefix(trimmed, "#"):
			continue
		}

		level := 0
		for level < len(trimmed) && trimmed[level] == '#' {
			level++
		}
		if level > 6 || level >= len(trimmed) || trimmed[level] != ' ' {
			// A hash run with no space after it is not a heading. It is a
			// comment, or a fragment somebody wrote in prose.
			continue
		}
		text := strings.TrimSpace(trimmed[level:])
		if text == "" {
			continue
		}

		// Every heading at this level or deeper is closed by this one. Its
		// section ends on the line before, and it stops being an ancestor.
		for len(stack) > 0 && stack[len(stack)-1].level >= level {
			out[stack[len(stack)-1].at].LastLine = i
			stack = stack[:len(stack)-1]
		}

		anchor := slug(text)
		used[anchor]++
		if used[anchor] > 1 {
			// The site's own slugger disambiguates a repeated heading the
			// same way, so an anchor here is an anchor there.
			anchor = fmt.Sprintf("%s-%d", anchor, used[anchor]-1)
		}
		trail := make([]string, 0, len(stack)+2)
		trail = append(trail, title)
		for _, ancestor := range stack {
			trail = append(trail, ancestor.text)
		}
		trail = append(trail, text)

		out = append(out, Heading{
			Level: level, Text: text, Anchor: anchor,
			Trail: strings.Join(trail, " > "),
			// Left open. Whatever closes it writes the real value, and the
			// sweep below closes the ones nothing did.
			FirstLine: i + 1, LastLine: 0,
		})
		stack = append(stack, openHeading{level: level, text: text, at: len(out) - 1})
	}
	// Whatever is still open runs to the end of the page.
	for i := range out {
		if out[i].LastLine == 0 {
			out[i].LastLine = len(lines)
		}
	}
	return out
}

// slug renders a heading as the fragment the site serves it at.
//
// It is github-slugger's rule, which is what Starlight uses: lowercase, drop
// everything that is not a letter, a digit or an underscore, and turn spaces
// into hyphens. The underscore SURVIVES, and that is not a detail here: half
// the headings in the MCP reference are tool names like
// rehearse_migration_safety, and an anchor that hyphenated them would be an
// anchor the site does not serve and this package cannot find.
func slug(text string) string {
	var b strings.Builder
	for _, r := range strings.ToLower(strings.TrimSpace(text)) {
		switch {
		case unicode.IsLetter(r) || unicode.IsDigit(r) || r == '_':
			b.WriteRune(r)
		case r == ' ' || r == '-':
			b.WriteRune('-')
		}
	}
	return strings.Trim(b.String(), "-")
}

// termsIn is the tokenizer both the index and a query use.
//
// One function for both, because two tokenizers is how a term that is indexed
// one way and looked up another silently matches nothing.
func termsIn(s string) map[string]int {
	out := map[string]int{}
	field := strings.Builder{}
	flush := func() {
		if field.Len() >= 2 {
			out[field.String()]++
		}
		field.Reset()
	}
	for _, r := range strings.ToLower(s) {
		if unicode.IsLetter(r) || unicode.IsDigit(r) || r == '_' {
			field.WriteRune(r)
			continue
		}
		flush()
	}
	flush()
	return out
}

