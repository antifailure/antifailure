// Package docs serves this build's own documentation to a caller that has to
// read it inside a budget.
//
// The problem it exists for is not "the documentation is not available". It is
// that 89 pages and 1.1 MB of Markdown is far more than any agent should pull
// into a conversation, so a tool that answers a narrow question with a whole
// page is worse than no tool at all: it costs the caller the room it needed to
// act on the answer. Everything here is built around that. A search returns
// excerpts and never pages, a listing costs a few hundred tokens rather than
// many thousands, a page is read by section, and every answer states what it
// did NOT return, because a silent truncation is a reader believing it has
// seen everything.
//
// The pages themselves are in pages.gen.go, generated by tools/docsembed from
// docs/src/content/docs. See that command for why they are embedded rather
// than read from disk: the MCP server is bound to the CALLER'S checkout, which
// is their application and has no copy of this repository's documentation in
// it.
package docs

import (
	"fmt"
	"math"
	"sort"
	"strings"
	"sync"
	"unicode"
)

// A Page is one documentation page as it ships.
type Page struct {
	// Path is the page's path under docs/src/content/docs, such as
	// "concepts/goldens.md". It is the identifier a caller passes back.
	Path string
	// Section is the top level directory, such as "concepts". The root
	// index.md has no section and reports "index".
	Section string
	// Title and Description come from the page's own frontmatter, which every
	// page on this site carries because Starlight requires a title.
	Title       string
	Description string
	// Body is the page with its frontmatter removed, so an offset into it is
	// an offset into the prose a reader sees.
	Body string
	// Lines is Body split on newlines, kept because every excerpt in this
	// package is measured in lines rather than in bytes.
	Lines []string
	// terms is every word on the page, for deciding how common a word is
	// across the corpus. Held per page rather than as one global count,
	// because a word's weight is how many PAGES carry it and a total that
	// counted a page twice would make a rare word look common.
	terms map[string]int
	// Headings are the page's own headings in document order.
	Headings []Heading
}

// A Heading is one section of a page.
type Heading struct {
	// Level is the number of leading hashes: 2 for "## Goldens".
	Level int
	// Text is the heading as written, with its Markdown left alone.
	Text string
	// Anchor is the fragment the site serves it at, which is also what a
	// caller passes to read just this section.
	Anchor string
	// Trail is the heading path from the top of the page, such as
	// "Bounded output > Why a page is not returned". It is what tells a
	// reader where an excerpt came from without returning the page.
	Trail string
	// FirstLine is the heading's own line, 1 based into Lines. LastLine is
	// the last line belonging to this section, which is the line before the
	// next heading at this level or above.
	FirstLine, LastLine int
}

// index is the parsed corpus, built once.
type index struct {
	pages    []*Page
	byPath   map[string]*Page
	sections []string
	// pagesWithTerm is how many pages contain each term, which is what makes
	// a query's common words cost almost nothing. See scoreOf.
	pagesWithTerm map[string]int
}

var (
	loadOnce sync.Once
	loaded   *index
)

// load parses the embedded pages once.
//
// Once rather than per call, because parsing 1.1 MB of Markdown on every
// search would be paid by the caller in latency for no benefit.
//
// It is NOT deferred until somebody asks a question, and saying so is the
// honest version: the MCP server publishes the real section names in the
// enum of its documentation tools, so building those schemas at startup
// parses the corpus at startup, for every session, whether or not anybody
// asks anything. That is the trade taken deliberately. A published enum a
// caller can read is worth more than the tens of milliseconds and few
// megabytes it costs, and the alternative, a hand written list of section
// names, is a second description of the directory layout able to disagree
// with it.
func load() *index {
	loadOnce.Do(func() { loaded = build(Pages) })
	return loaded
}

// build parses a set of pages. Separate from load so a test can build an
// index from pages it wrote itself.
func build(pages map[string]string) *index {
	ix := &index{
		byPath:        make(map[string]*Page, len(pages)),
		pagesWithTerm: map[string]int{},
	}
	paths := make([]string, 0, len(pages))
	for path := range pages {
		paths = append(paths, path)
	}
	sort.Strings(paths)

	seenSection := map[string]bool{}
	for _, path := range paths {
		page := parse(path, pages[path])
		ix.pages = append(ix.pages, page)
		ix.byPath[path] = page
		if !seenSection[page.Section] {
			seenSection[page.Section] = true
			ix.sections = append(ix.sections, page.Section)
		}
		page.terms = termsIn(page.Title + " " + page.Description + " " + page.Body)
		for term := range page.terms {
			ix.pagesWithTerm[term]++
		}
	}
	sort.Strings(ix.sections)
	return ix
}

// PageCount is how many pages this build ships.
func PageCount() int { return len(load().pages) }

// Sections are the top level groups, in order.
func Sections() []string { return append([]string(nil), load().sections...) }

// The package level entry points are one line each over the index they read,
// so that a test can build an index from pages it wrote itself and exercise
// exactly the same code the shipped corpus goes through. A search that is only
// ever tested against 92 real pages is a search whose behaviour at the edges
// nobody can arrange.

// Listing is one page in a table of contents.
type Listing struct {
	Path        string
	Section     string
	Title       string
	Description string
	Headings    int
	Chars       int
}

// List returns the table of contents, narrowed to one section when section is
// not empty. An unknown section returns nothing, and the caller says so.
func List(section string) []Listing { return load().list(section) }

func (ix *index) list(section string) []Listing {
	out := []Listing{}
	for _, p := range ix.pages {
		if section != "" && p.Section != section {
			continue
		}
		out = append(out, Listing{
			Path: p.Path, Section: p.Section, Title: p.Title,
			Description: p.Description, Headings: len(p.Headings), Chars: len(p.Body),
		})
	}
	return out
}

// Lookup finds a page by path, tolerantly.
//
// Tolerant on purpose, and only here. A caller that read "concepts/goldens.md"
// out of a search result passes it back exactly; a caller that inferred a path
// from a URL passes "/docs/concepts/goldens" or "concepts/goldens", and
// refusing those would spend a round trip teaching an agent a file extension.
// Nothing is guessed: each candidate is an exact key or it is not.
func Lookup(path string) (*Page, bool) { return load().lookup(path) }

func (ix *index) lookup(path string) (*Page, bool) {
	cleaned := strings.TrimSpace(path)
	cleaned = strings.TrimPrefix(cleaned, "/")
	cleaned = strings.TrimPrefix(cleaned, "docs/")
	cleaned = strings.TrimSuffix(cleaned, "/")
	for _, candidate := range []string{
		cleaned,
		cleaned + ".md",
		strings.TrimSuffix(cleaned, ".md") + "/index.md",
	} {
		if p, ok := ix.byPath[candidate]; ok {
			return p, true
		}
	}
	return nil, false
}

// Near returns the paths closest to one that was not found, so a refusal can
// name what the caller probably meant.
func Near(path string, limit int) []string { return load().near(path, limit) }

func (ix *index) near(path string, limit int) []string {
	wanted := termsIn(strings.ReplaceAll(strings.TrimSuffix(path, ".md"), "/", " "))
	type scored struct {
		path  string
		score int
	}
	var ranked []scored
	for _, p := range ix.pages {
		score := 0
		for term := range termsIn(strings.ReplaceAll(strings.TrimSuffix(p.Path, ".md"), "/", " ")) {
			if _, wants := wanted[term]; wants {
				score += 10
			}
		}
		for term := range wanted {
			if strings.Contains(p.Path, term) {
				score++
			}
		}
		if score > 0 {
			ranked = append(ranked, scored{p.Path, score})
		}
	}
	sort.SliceStable(ranked, func(i, j int) bool { return ranked[i].score > ranked[j].score })
	out := []string{}
	for _, r := range ranked {
		if len(out) >= limit {
			break
		}
		out = append(out, r.path)
	}
	return out
}

// FindHeading returns a page's section by anchor or by the heading's own text.
func (p *Page) FindHeading(anchor string) (*Heading, bool) {
	wanted := slug(anchor)
	for i := range p.Headings {
		if p.Headings[i].Anchor == wanted {
			return &p.Headings[i], true
		}
	}
	return nil, false
}

// Anchors lists a page's section anchors, which is what a caller needs to ask
// for one of them.
func (p *Page) Anchors() []string {
	out := make([]string, 0, len(p.Headings))
	for _, h := range p.Headings {
		out = append(out, h.Anchor)
	}
	return out
}

// Text returns the lines from first to last inclusive, both 1 based.
func (p *Page) Text(first, last int) string {
	if first < 1 {
		first = 1
	}
	if last > len(p.Lines) {
		last = len(p.Lines)
	}
	if first > last {
		return ""
	}
	return strings.Join(p.Lines[first-1:last], "\n")
}

