package generated

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func TestTheMarkerBeforeThePackageClauseCounts(t *testing.T) {
	if !IsSource([]byte("// Code generated by tools/docsembed. DO NOT EDIT.\n\npackage docs\n")) {
		t.Fatal("a file carrying the convention's own sentence must be recognised")
	}
}

func TestAHandWrittenFileIsNotGenerated(t *testing.T) {
	if IsSource([]byte("// Package p does a thing.\npackage p\n")) {
		t.Fatal("an ordinary file must not excuse itself")
	}
}

func TestQuotingTheMarkerAfterThePackageClauseDoesNotCount(t *testing.T) {
	// The generator that WRITES the sentence has it in a string literal. A
	// rule that read the whole file would let every generator in this
	// repository exempt itself from every gate, which is the opposite of what
	// this is for.
	src := "package main\n\nconst header = \"// Code generated by tools/x. DO NOT EDIT.\"\n"
	if IsSource([]byte(src)) {
		t.Fatal("a file quoting the marker after the package clause must still be checked")
	}

	// The same file with no leading comment at all, which is the shape that
	// found the hole: with the clause on the very first byte there is no
	// newline before it, so a search for "\npackage " finds nothing and the
	// whole file gets read.
	first := "package main\n// Code generated by tools/x. DO NOT EDIT.\nconst c = 1\n"
	if IsSource([]byte(first)) {
		t.Fatal("a file whose package clause is the first line must still be checked")
	}
}

func TestAFileThatCannotBeReadIsCheckedRatherThanSkipped(t *testing.T) {
	// Failing open would mean an unreadable file quietly exempting itself from
	// every gate that asks, which is a pass nobody earned.
	if Is(filepath.Join(t.TempDir(), "absent.go")) {
		t.Fatal("an unreadable file must be reported as not generated")
	}
}

func TestTheRealGeneratedFilesAreRecognisedAndTheHandWrittenOnesAreNot(t *testing.T) {
	root := filepath.Join("..", "..", "..")
	for _, rel := range []string{
		"engine/internal/docs/pages.gen.go",
		"engine/internal/errors/codes.gen.go",
		"engine/internal/proxyimage/sources.gen.go",
	} {
		path := filepath.Join(root, filepath.FromSlash(rel))
		if _, err := os.Stat(path); err != nil {
			t.Fatalf("%s is not where this test expects it: %v. Point the test at the "+
				"new path rather than letting it pass by finding nothing.", rel, err)
		}
		if !Is(path) {
			t.Errorf("%s is generated and was not recognised", rel)
		}
	}
	for _, rel := range []string{
		"engine/internal/docs/docs.go",
		"tools/docsembed/main.go",
	} {
		path := filepath.Join(root, filepath.FromSlash(rel))
		body, err := os.ReadFile(path)
		if err != nil {
			t.Fatalf("%s: %v", rel, err)
		}
		if !strings.Contains(string(body), "package ") {
			t.Fatalf("%s does not look like Go, so this proved nothing", rel)
		}
		if Is(path) {
			t.Errorf("%s is hand written and excused itself", rel)
		}
	}
}
